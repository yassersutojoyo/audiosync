"""Writes the design token files from brand/tokens.json.

Writes:
  Sources/AudioSync/BrandTokens.swift   the values the Mac app's Brand constants use
  desktop/ui/tokens.slint               the Windows app's Tokens global (follows light/dark)
  desktop/src/tokens.rs                 the same colors for the Windows app's contrast test
  site/index.html                       the CSS variables between the tokens:begin/end markers

Every output is deterministic, so CI runs this and fails on any diff.

Usage: python3 -I scripts/brand/tokens.py [--check]   (from the repository root)
  --check  write nothing; exit 1 if any output is out of date
"""
import json
import re
import sys

TOKENS = 'brand/tokens.json'
SWIFT = 'Sources/AudioSync/BrandTokens.swift'
SLINT = 'desktop/ui/tokens.slint'
RUST = 'desktop/src/tokens.rs'
SITE = 'site/index.html'

SITE_BEGIN = '/* tokens:begin (generated by scripts/brand/tokens.py from brand/tokens.json; edit those) */'
SITE_END = '/* tokens:end */'

HEADER = 'Generated by scripts/brand/tokens.py from brand/tokens.json. Do not edit.'


def entries(group):
    """The tokens of a group, without its $description."""
    return [(name, value) for name, value in group.items() if not name.startswith('$')]


def rgb(hex_color):
    match = re.fullmatch(r'#([0-9A-Fa-f]{2})([0-9A-Fa-f]{2})([0-9A-Fa-f]{2})', hex_color)
    if not match:
        sys.exit(f'{TOKENS}: {hex_color!r} is not a #RRGGBB color')
    return tuple(int(part, 16) for part in match.groups())


def kebab(name):
    return re.sub(r'([A-Z])', lambda m: '-' + m.group(1).lower(), name)


def number(value):
    """1 -> '1', 0.7 -> '0.7', 12.0 -> '12'."""
    return f'{value:g}'


def css_alpha(value):
    """0.55 -> '.55', as the site writes it."""
    text = number(value)
    return text[1:] if text.startswith('0.') else text


def doc_lines(text, indent, prefix):
    """A description as comment lines of at most about 100 characters."""
    words, lines, line = text.split(), [], ''
    for word in words:
        if line and len(indent) + len(prefix) + len(line) + 1 + len(word) > 100:
            lines.append(line)
            line = word
        else:
            line = f'{line} {word}' if line else word
    if line:
        lines.append(line)
    return [f'{indent}{prefix}{line}' for line in lines]


# ---- Swift ----------------------------------------------------------------

def swift_rgb(hex_color):
    r, g, b = rgb(hex_color)
    return f'BrandRGB(red: {r} / 255, green: {g} / 255, blue: {b} / 255)'


def swift(tokens):
    out = [f'// {HEADER}', '', 'import CoreGraphics', '',
           '/// An sRGB color as 0-1 components.',
           'struct BrandRGB {',
           '    let red: Double',
           '    let green: Double',
           '    let blue: Double',
           '}', '',
           "/// AudioSync's design tokens (brand/tokens.json), shared with the Windows app",
           "/// and the website. `Brand` turns them into the app's colors and fonts.",
           'enum BrandTokens {']
    for appearance in ('light', 'dark'):
        out.append(f'    /// Colors in {appearance} appearance.')
        out.append(f'    enum {appearance.capitalize()} {{')
        for name, token in entries(tokens['color']):
            out += doc_lines(token['description'], '        ', '/// ')
            out.append(f'        static let {name} = {swift_rgb(token[appearance])}')
        out.append('    }')
        out.append('')
    out.append('    enum Opacity {')
    for name, token in entries(tokens['opacity']):
        out += doc_lines(token['description'], '        ', '/// ')
        out.append(f'        static let {name}: Double = {number(token["value"])}')
    out.append('    }')
    out.append('')
    brand = tokens['typography']['brand']
    out.append('    enum Typography {')
    out += doc_lines(brand['description'], '        ', '/// ')
    out.append(f'        static let brandFontName = "{brand["postScriptName"]}"')
    out.append('        /// Letter spacing of the wordmark, in em.')
    out.append(f'        static let brandTracking: CGFloat = {number(brand["tracking"])}')
    out.append(f'        static let wordmarkSize: CGFloat = {number(tokens["typography"]["size"]["wordmark"])}')
    out.append('    }')
    for group in ('spacing', 'radius'):
        out.append('')
        out += doc_lines(tokens[group]['$description'], '    ', '/// ')
        out.append(f'    enum {group.capitalize()} {{')
        for name, value in entries(tokens[group]):
            out.append(f'        static let {name}: CGFloat = {number(value)}')
        out.append('    }')
    out.append('}')
    return '\n'.join(out) + '\n'


# ---- Slint ----------------------------------------------------------------

def slint_hex(hex_color):
    return hex_color.lower()


def slint(tokens):
    out = [f'// {HEADER}', '//',
           "// AudioSync's design tokens (brand/tokens.json). Colors follow the system's",
           "// light or dark mode through the style's palette.", '',
           'import { Palette } from "std-widgets.slint";', '',
           'export global Tokens {',
           '    // True while Windows uses dark mode for apps.',
           '    out property <bool> dark: Palette.color-scheme == ColorScheme.dark;']
    for name, token in entries(tokens['color']):
        out.append('')
        out += doc_lines(token['description'], '    ', '// ')
        light, dark = slint_hex(token['light']), slint_hex(token['dark'])
        value = light if light == dark else f'root.dark ? {dark} : {light}'
        out.append(f'    out property <color> {kebab(name)}: {value};')
    for name, token in entries(tokens['opacity']):
        out.append('')
        out += doc_lines(token['description'], '    ', '// ')
        out.append(f'    out property <float> {kebab(name)}-opacity: {number(token["value"])};')
    out.append('')
    out.append('    // Secondary text: the text color at the secondary-text opacity, as on the Mac.')
    out.append('    out property <color> secondary-text: root.text.with-alpha(root.secondary-text-opacity);')
    brand = tokens['typography']['brand']
    out.append('')
    out += doc_lines(brand['description'], '    ', '// ')
    out.append(f'    out property <string> brand-font: "{brand["family"]}";')
    out.append(f'    out property <int> brand-font-weight: {brand["weight"]};')
    out.append('    // Letter spacing of the wordmark, in em.')
    out.append(f'    out property <float> brand-tracking: {number(brand["tracking"])};')
    for name, value in entries(tokens['typography']['size']):
        out.append(f'    out property <length> font-size-{kebab(name)}: {number(value)}px;')
    for group in ('spacing', 'radius'):
        out.append('')
        out += doc_lines(tokens[group]['$description'], '    ', '// ')
        for name, value in entries(tokens[group]):
            out.append(f'    out property <length> {group}-{kebab(name)}: {number(value)}px;')
    out.append('}')
    return '\n'.join(out) + '\n'


# ---- Rust (for the contrast test) ----------------------------------------

def rust(tokens):
    out = [f'// {HEADER}', '',
           "//! The Windows app's colors and the text-on-background pairs it draws, for",
           '//! the contrast test (the UI itself reads `ui/tokens.slint`).', '',
           '/// A color token: its name in brand/tokens.json and its light and dark sRGB values.',
           'pub struct ColorToken {',
           '    pub name: &\'static str,',
           '    pub light: [u8; 3],',
           '    pub dark: [u8; 3],',
           '}', '',
           'pub const COLORS: &[ColorToken] = &[']
    for name, token in entries(tokens['color']):
        light, dark = rgb(token['light']), rgb(token['dark'])
        out.append('    ColorToken {')
        out.append(f'        name: "{name}",')
        out.append(f'        light: [{light[0]}, {light[1]}, {light[2]}],')
        out.append(f'        dark: [{dark[0]}, {dark[1]}, {dark[2]}],')
        out.append('    },')
    out.append('];')
    out.append('')
    out.append('/// Opacities by name (brand/tokens.json `opacity`).')
    out.append('pub const OPACITIES: &[(&str, f64)] = &[')
    for name, token in entries(tokens['opacity']):
        value = number(token['value'])
        out.append(f'    ("{name}", {value if "." in value else value + ".0"}),')
    out.append('];')
    out.append('')
    out.append('/// Text (`color` or `color@opacity`) on background, every pair the UI draws.')
    out.append('pub const CONTRAST_PAIRS: &[(&str, &str)] = &[')
    for foreground, background in tokens['contrast']['pairs']:
        out.append(f'    ("{foreground}", "{background}"),')
    out.append('];')
    return '\n'.join(out) + '\n'


# ---- Site -----------------------------------------------------------------

def css_value(tokens, reference):
    group, name = reference.split('.', 1)
    token = tokens[group][name]
    if group == 'color':
        # The site has one appearance, the light one.
        return token['light'].lower()
    if group == 'alpha':
        r, g, b = rgb(token['color'])
        return f'rgba({r},{g},{b},{css_alpha(token["opacity"])})'
    if group == 'shadow':
        r, g, b = rgb(token['color'])
        offsets = ' '.join(f'{number(token[key])}px' if token[key] else '0'
                           for key in ('x', 'y', 'blur', 'spread'))
        return f'{offsets} rgba({r},{g},{b},{css_alpha(token["opacity"])})'
    if group == 'radius':
        return f'{number(token)}px'
    sys.exit(f'{TOKENS}: the site cannot use {reference}')


def site(tokens, html):
    begin, end = html.find(SITE_BEGIN), html.find(SITE_END)
    if begin < 0 or end < begin:
        sys.exit(f'{SITE}: the {SITE_BEGIN} ... {SITE_END} markers are missing')
    line_start = html.rfind('\n', 0, begin) + 1
    indent = html[line_start:begin]
    lines = [SITE_BEGIN]
    lines += [f'{indent}{var}:{css_value(tokens, ref)};' for var, ref in entries(tokens['site'])]
    lines.append(f'{indent}{SITE_END}')
    return html[:begin] + '\n'.join(lines) + html[end + len(SITE_END):]


def main():
    check = sys.argv[1:] == ['--check']
    if sys.argv[1:] and not check:
        sys.exit('usage: python3 -I scripts/brand/tokens.py [--check]')
    with open(TOKENS, encoding='utf-8') as f:
        tokens = json.load(f)
    with open(SITE, encoding='utf-8') as f:
        html = f.read()
    outputs = {SWIFT: swift(tokens), SLINT: slint(tokens), RUST: rust(tokens), SITE: site(tokens, html)}
    stale = []
    for path, text in outputs.items():
        try:
            with open(path, encoding='utf-8') as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current == text:
            continue
        stale.append(path)
        if not check:
            # Always LF, so a run on Windows writes the same bytes as CI.
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
    if check and stale:
        sys.exit('out of date: ' + ', '.join(stale))
    print('up to date' if not stale else 'wrote ' + ', '.join(stale))


if __name__ == '__main__':
    main()
