"""Builds the derived brand files from brand/audiosync-mark.svg.

Writes:
  brand/audiosync-icon.svg        app icon, light (macOS icon grid: 824 pt tile on 1024)
  brand/audiosync-icon-dark.svg   app icon, dark
  Sources/AudioSync/BrandMark.swift   the mark as a SwiftUI Shape

Placement follows the design sheet: the mark spans 62.7% of the tile's width and sits
1.1% left of and 0.9% below the tile's center (optical centering for the heavy stem).

Usage: python3 compose.py   (run from the repository root)
"""
import re
import xml.etree.ElementTree as ET

MARK = 'brand/audiosync-mark.svg'
SVG = '{http://www.w3.org/2000/svg}'

CANVAS, TILE, RADIUS = 1024, 824, 185.4
MARK_WIDTH_RATIO = 0.627
OFFSET = (-0.0113, 0.0094)   # fraction of the tile size

VARIANTS = {
    'brand/audiosync-icon.svg': {'top': '#FEFEFE', 'bottom': '#F2F2F2', 'mark': '#1C9F91', 'title': 'AudioSync'},
    'brand/audiosync-icon-dark.svg': {'top': '#3B514F', 'bottom': '#223834', 'mark': '#63DAC2', 'title': 'AudioSync'},
}


def read_mark():
    root = ET.parse(MARK).getroot()
    _, _, w, h = (float(v) for v in root.get('viewBox').split())
    d = root.find(SVG + 'path').get('d')
    return w, h, d


def icon_svg(w, h, d, v):
    tile0 = (CANVAS - TILE) / 2
    scale = TILE * MARK_WIDTH_RATIO / w
    cx = CANVAS / 2 + OFFSET[0] * TILE
    cy = CANVAS / 2 + OFFSET[1] * TILE
    tx, ty = cx - w * scale / 2, cy - h * scale / 2
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {CANVAS} {CANVAS}">
  <title>{v['title']}</title>
  <defs>
    <linearGradient id="tile" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{v['top']}"/>
      <stop offset="1" stop-color="{v['bottom']}"/>
    </linearGradient>
  </defs>
  <rect x="{tile0:g}" y="{tile0:g}" width="{TILE}" height="{TILE}" rx="{RADIUS}" fill="url(#tile)"/>
  <path transform="translate({tx:.2f} {ty:.2f}) scale({scale:.6f})" fill="{v['mark']}" d="{d}"/>
</svg>
'''


def swift_shape(w, h, d):
    # tidy-svg.py writes only absolute M/L/C/Z with plain decimals; refuse anything else
    # rather than silently drawing a different shape.
    if not re.fullmatch(r'(?:\s*(?:[MLCZ]|-?\d+(?:\.\d+)?))*\s*', d):
        raise SystemExit(f'{MARK}: unsupported path syntax (expected absolute M/L/C/Z and plain numbers)')
    tokens = re.findall(r'[MLCZ]|-?\d+(?:\.\d+)?', d)
    lines, i = [], 0

    def pt():
        nonlocal i
        x, y = tokens[i], tokens[i + 1]
        i += 2
        return f'p({x}, {y})'

    while i < len(tokens):
        cmd = tokens[i]
        i += 1
        if cmd == 'M':
            lines.append(f'        path.move(to: {pt()})')
        elif cmd == 'L':
            lines.append(f'        path.addLine(to: {pt()})')
        elif cmd == 'C':
            c1, c2, end = pt(), pt(), pt()
            lines.append(f'        path.addCurve(to: {end}, control1: {c1}, control2: {c2})')
        elif cmd == 'Z':
            lines.append('        path.closeSubpath()')
    body = '\n'.join(lines)
    return f'''// Generated by scripts/brand/compose.py from brand/audiosync-mark.svg — do not edit.
import SwiftUI

/// The AudioSync logo mark, drawn from the brand artwork. Fill it with a color or style;
/// it keeps its aspect ratio and centers itself in the frame it is given.
struct BrandMark: Shape {{
    static let aspectRatio: CGFloat = {w:g} / {h:g}

    func path(in rect: CGRect) -> Path {{
        let scale = min(rect.width / {w:g}, rect.height / {h:g})
        let originX = rect.midX - {w:g} * scale / 2
        let originY = rect.midY - {h:g} * scale / 2
        func p(_ x: CGFloat, _ y: CGFloat) -> CGPoint {{
            CGPoint(x: originX + x * scale, y: originY + y * scale)
        }}
        var path = Path()
{body}
        return path
    }}
}}
'''


def main():
    w, h, d = read_mark()
    for out, v in VARIANTS.items():
        with open(out, 'w') as f:
            f.write(icon_svg(w, h, d, v))
        print(f'wrote {out}')
    with open('Sources/AudioSync/BrandMark.swift', 'w') as f:
        f.write(swift_shape(w, h, d))
    print('wrote Sources/AudioSync/BrandMark.swift')


if __name__ == '__main__':
    main()
